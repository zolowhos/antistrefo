// A memory form, selected by the reg field.
#define XM(op, reg, mn, ops) XR(op, XS_L, XP_ANY, XM_MEM, reg, X_ANY, XW_ANY, 0, 0, 0, 0, mn, ops)
// A run of eight register forms: the low three bits name the stack register.
#define XS(op, reg, mn, ops) XR(op, XS_L, XP_ANY, XM_REG, reg, X_ANY, XW_ANY, 0, 0, 0, 0, mn, ops)
// One register form: the whole ModRM byte is the opcode.
#define X1(op, reg, rm, mn) XR(op, XS_L, XP_ANY, XM_REG, reg, rm, XW_ANY, 0, 0, 0, 0, mn, "")

