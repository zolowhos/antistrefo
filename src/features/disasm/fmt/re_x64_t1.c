// A form with an explicit prefix, ModRM shape and W bit, in the legacy space.
#define XP(op, pfx, mod, reg, rm, w, fl, mn, ops) \
    XR(op, XS_L, pfx, mod, reg, rm, w, 0, 0, 0, fl, mn, ops)
// One register encoding of group 7: the whole ModRM byte names it.
#define G7(rm8, pfx, mn) XP(0x01, pfx, REG, ((rm8) >> 3) & 7, (rm8) & 7, XW_ANY, 0, mn, "")

// The sixteen conditions, in encoding order.
