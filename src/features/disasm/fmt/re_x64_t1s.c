// Module: feature (C11).
// Owns: prefix-selected 0F 10..17, 28..2F, 50..7F, C2..C6, D0..FE with VEX/EVEX forms.
// Depends: re_x64_form.h. Sorted by opcode; first hit wins. EVEX overrides are in t1e.
#include "features/disasm/fmt/re_x64_form.h"

#define KZ XF_KZ
#define ER XF_ER
#define SAE XF_SAE
#define NP XP_NP
#define P66 XP_66
#define PF3 XP_F3
#define PF2 XP_F2
#define ANY XM_ANY
#define MEM XM_MEM
#define REG XM_REG

// A row in the given spaces, prefix and ModRM shape, with EVEX element and flags.
#define V(op, sp, pfx, mod, bc, fl, mn, ops) \
    XR(op, sp, pfx, mod, X_ANY, X_ANY, XW_ANY, 0, 0, bc, fl, mn, ops)
// Packed single, packed double, scalar single, scalar double, in all three spaces.
#define PS(op, fl, mn, ops) V(op, XS_LVE, NP, ANY, XB_4 | XE_W0, KZ | fl, mn, ops)
#define PD(op, fl, mn, ops) V(op, XS_LVE, P66, ANY, XB_8 | XE_W1, KZ | fl, mn, ops)
#define SS(op, fl, mn, ops) V(op, XS_LVE, PF3, ANY, XE_W0, KZ | fl, mn, ops)
#define SD(op, fl, mn, ops) V(op, XS_LVE, PF2, ANY, XE_W1, KZ | fl, mn, ops)
// The four float forms of one arithmetic opcode.
#define FP4(op, fl, a, b, c, d)                                                         \
    PS(op, fl, a, "Vx,Hx,Wx"), PD(op, fl, b, "Vx,Hx,Wx"), SS(op, fl, c, "Vdq,Hdq,Wss"), \
        SD(op, fl, d, "Vdq,Hdq,Wsd")
// The MMX form without a prefix and the SSE2 form under 0x66 of one integer opcode. The
// EVEX element is byte or word (no broadcast), dword or qword.
#define MX(op, mn, mops) V(op, XS_L, NP, ANY, 0, 0, mn, mops)
#define IB(op, mn, ops) MX(op, mn, "Pq,Qq"), V(op, XS_LVE, P66, ANY, 0, KZ, mn, ops)
#define ID(op, mn, ops) MX(op, mn, "Pq,Qq"), V(op, XS_LVE, P66, ANY, XB_4 | XE_W0, KZ, mn, ops)
#define IQ(op, mn, ops) MX(op, mn, "Pq,Qq"), V(op, XS_LVE, P66, ANY, XB_8 | XE_W1, KZ, mn, ops)
// The shifts by a count in an xmm register or m128: the count never broadcasts.
#define SD0(op, mn, ops) MX(op, mn, "Pq,Qq"), V(op, XS_LVE, P66, ANY, XE_W0, KZ, mn, ops)
#define SQ1(op, mn, ops) MX(op, mn, "Pq,Qq"), V(op, XS_LVE, P66, ANY, XE_W1, KZ, mn, ops)
// The SSE2 integer forms that have no EVEX form under this name.
#define IV(op, mn, ops) MX(op, mn, "Pq,Qq"), V(op, XS_LV, P66, ANY, 0, 0, mn, ops)
// A shift group row: the MMX form and the vector form, selected by ModRM.reg.
#define SH(op, reg, mn, bc)                                                      \
    XR(op, XS_L, NP, REG, reg, X_ANY, XW_ANY, 0, 0, 0, 0, mn, "Nq,Ib"),          \
        XR(op, XS_LV, P66, REG, reg, X_ANY, XW_ANY, 0, 0, 0, 0, mn, "Hx,Ux,Ib"), \
        XR(op, XS_E, P66, ANY, reg, X_ANY, XW_ANY, 0, 0, bc, KZ, "v" mn, "Hx,Wx,Ib")

